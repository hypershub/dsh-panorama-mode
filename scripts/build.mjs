#!/usr/bin/env node
/**
 * Concatenate the authored client parts into the single browser bundle the
 * Harness module loader expects. Parts share one closure on purpose: the
 * loader only resolves the frozen platform module table, so there is no
 * relative require to split helpers across files at runtime.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PARTS = ['00-head', 'brand-logo', '10-css', '20-orb', '30-model', '35-results', '40-panels', '50-settings', '60-shell', '70-slots']

const chunks = []
for (const part of PARTS) {
  const file = path.join(root, 'src', 'client', `${part}.js`)
  chunks.push(`/* ── src/client/${part}.js ───────────────────────────────────────────── */\n${await readFile(file, 'utf8')}`)
}

const tokenizer = await build({stdin:{contents:'export * from "marked"',resolveDir:root},bundle:true,write:false,format:'iife',globalName:'PanoramaMarkdown',platform:'browser',minify:true})
const banner = `/* dsh-panorama-mode · client bundle.
 * Generated by scripts/build.mjs from src/client/*.js — edit those parts, not this file.
 */
window.__ModuleLoader__.load({
  id: '@hypershub/dsh-panorama-mode',
  factory(require) {
    const React = require('react')
    const h = React.createElement
${tokenizer.outputFiles[0].text}
    const marked = PanoramaMarkdown.marked
`

const output = `${banner}${chunks.join('\n')}\n  },\n})\n`
const target = path.join(root, 'client.js')
await writeFile(target, output)
console.log(`built ${path.relative(root, target)} (${output.length} bytes) from ${PARTS.length} parts`)
